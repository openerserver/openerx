import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const lockBytes = readFileSync(path.join(root, "package-lock.json"));
const lock = JSON.parse(lockBytes);
const inventoryPath = path.join(root, "third-party", "notices.json");
const textPath = path.join(root, "THIRD_PARTY_LICENSES.txt");
const sha = (value) => createHash("sha256").update(value).digest("hex");
const legalName = /(?:^|[-_.])(licen[sc]e|notice|copying)(?:[-_.]|$)/iu;
const packages = Object.entries(lock.packages)
  .filter(([key, value]) => key.includes("node_modules/") && !value.link)
  .sort(([a], [b]) => a.localeCompare(b, "en"));
const nameOf = (key, value) => value.name ?? key.split("node_modules/").at(-1);

function readLegalFiles(directory, relative = "", depth = 0) {
  if (!existsSync(directory)) return [];
  const result = [];
  for (const file of readdirSync(directory).sort()) {
    const absolute = path.join(directory, file);
    const stat = statSync(absolute);
    if (stat.isFile() && legalName.test(file) && stat.size < 2_000_000) {
      result.push({
        path: `${relative}${file}`,
        text: readFileSync(absolute, "utf8").replaceAll("\r\n", "\n").trim(),
      });
    } else if (stat.isDirectory() && depth < 2 && /^(?:licenses?|notices?)$/iu.test(file)) {
      result.push(...readLegalFiles(absolute, `${relative}${file}/`, depth + 1));
    }
  }
  if (!result.length && !relative) {
    const readme = ["README.md", "readme.md", "README.markdown", "README"].find((file) =>
      existsSync(path.join(directory, file)),
    );
    if (readme) {
      const text = readFileSync(path.join(directory, readme), "utf8").replaceAll("\r\n", "\n");
      const section = /(?:^|\n)#{1,3}\s*(?:License|Copyright)[^\n]*\n([\s\S]*)/iu.exec(text)?.[0];
      if (
        section &&
        /(?:Permission is hereby granted|Redistribution and use|Permission to use, copy)/iu.test(
          section,
        )
      )
        result.push({ path: readme, text: section.trim() });
    }
  }
  return result.filter(({ text }) => text.length > 50 && !text.includes("\0"));
}

function render(inventory) {
  let output =
    "OpenERX — third-party copyright and license texts\nGenerated by npm run notices:update. Do not edit by hand.\nIncludes build/dev dependencies as well as runtime dependencies.\nElectron additionally ships LICENSE and LICENSES.chromium.html.\n";
  for (const item of inventory.packages) {
    output += `\n${"=".repeat(78)}\n${item.name}@${item.version}\nSPDX: ${item.license}\nLock path: ${item.path}\nPackage: ${item.resolved}\nSource: ${item.source}\n`;
    if (item.attribution) output += `Upstream attribution: ${JSON.stringify(item.attribution)}\n`;
    if (item.evidence?.includes("review-required"))
      output += `Evidence: ${item.evidence}. The package omitted a release-specific license file; verify attribution before redistribution.\n`;
    for (const document of item.documents)
      output += `\n--- ${document.source} (${document.path}) ---\n${inventory.texts[document.sha256]}\n`;
  }
  return output;
}

const requestCache = new Map();
async function request(url, json = false) {
  const key = `${json}:${url}`;
  if (!requestCache.has(key))
    requestCache.set(
      key,
      (async () => {
        const response = await fetch(url, { signal: AbortSignal.timeout(20_000) });
        if (!response.ok) return null;
        return json ? response.json() : response.text();
      })(),
    );
  return requestCache.get(key);
}

function githubRepository(repository) {
  const url = typeof repository === "string" ? repository : repository?.url;
  if (!url) return null;
  const match = /github\.com[:/]([^/]+\/[^/#]+?)(?:\.git)?(?:#.*)?$/u.exec(url);
  if (match) return match[1];
  return /^[\w.-]+\/[\w.-]+$/u.test(url) ? url : null;
}

async function generate() {
  const inventory = { schemaVersion: 1, lockSha256: sha(lockBytes), packages: [], texts: {} };
  const previous = existsSync(inventoryPath)
    ? JSON.parse(readFileSync(inventoryPath, "utf8"))
    : null;
  const cached = new Map(
    previous?.packages.map((item) => [`${item.name}@${item.version}:${item.integrity}`, item]) ??
      [],
  );
  const local = packages.map(([key, value]) => {
    const directory = path.join(root, key);
    const metadataPath = path.join(directory, "package.json");
    const metadata = existsSync(metadataPath)
      ? JSON.parse(readFileSync(metadataPath, "utf8"))
      : null;
    return {
      key,
      value,
      metadata,
      documents: metadata?.version === value.version ? readLegalFiles(directory) : [],
    };
  });
  const failures = [];
  for (const { key, value, metadata, documents: localDocuments } of local) {
    const name = nameOf(key, value);
    const officialSheetJs =
      name === "xlsx" &&
      value.version === "0.20.3" &&
      value.resolved === "https://cdn.sheetjs.com/xlsx-0.20.3/xlsx-0.20.3.tgz";
    if (
      !value.integrity ||
      (!value.resolved?.startsWith("https://registry.npmjs.org/") && !officialSheetJs)
    )
      throw new Error(`UNPINNED_DEPENDENCY:${key}`);
    const cachedItem = cached.get(`${name}@${value.version}:${value.integrity}`);
    if (cachedItem && cachedItem.license === value.license) {
      inventory.packages.push({ ...cachedItem, path: key });
      for (const document of cachedItem.documents)
        inventory.texts[document.sha256] = previous.texts[document.sha256];
      continue;
    }
    let info = metadata;
    let evidence = "distributed-or-release-source";
    let documents = localDocuments.map((doc) => ({ ...doc, source: value.resolved }));
    // Platform binary packages inherit the license files from their exact-version
    // wrapper when the wrapper explicitly declares that optional package.
    if (!documents.length) {
      const wrapper = local.find(
        (candidate) =>
          candidate.documents.length &&
          candidate.metadata?.optionalDependencies?.[name] === value.version &&
          candidate.value.license === value.license,
      );
      if (wrapper) {
        documents = wrapper.documents.map((doc) => ({ ...doc, source: wrapper.value.resolved }));
        info ??= wrapper.metadata;
      }
    }
    let repository = githubRepository(info?.repository);
    let source = repository
      ? `https://github.com/${repository}`
      : (info?.homepage ??
        `https://www.npmjs.com/package/${encodeURIComponent(name)}/v/${value.version}`);
    if (!documents.length) {
      const registryInfo = await request(
        `https://registry.npmjs.org/${encodeURIComponent(name)}/${value.version}`,
        true,
      );
      info = registryInfo ?? info;
      repository = githubRepository(info?.repository);
      const refs =
        info?.gitHead && /^[a-f0-9]{40}$/u.test(info.gitHead)
          ? [info.gitHead]
          : [`v${value.version}`, value.version, `${name}@${value.version}`];
      if (repository) {
        const directory = typeof info.repository === "object" ? info.repository.directory : null;
        for (const ref of refs) {
          for (const prefix of [...new Set([directory ? `${directory}/` : "", ""])]) {
            for (const filename of [
              "LICENSE",
              "LICENSE.md",
              "LICENSE-MIT",
              "license",
              "LICENSE.txt",
              "COPYING",
              "LICENCE",
              "license.md",
            ]) {
              const url = `https://raw.githubusercontent.com/${repository}/${ref}/${prefix}${filename}`;
              const text = await request(url);
              if (typeof text === "string" && text.length > 100 && !text.startsWith("<!DOCTYPE")) {
                documents.push({
                  path: `${prefix}${filename}`,
                  source: url,
                  text: text.replaceAll("\r\n", "\n").trim(),
                });
                source = `https://github.com/${repository}/tree/${ref}`;
                break;
              }
            }
            if (documents.length) break;
          }
          if (documents.length) break;
        }
      }
    }
    if (!documents.length) {
      // Some publishers omit legal files and release tags. Retain provenance;
      // never silently assign OpenERX's own license to third-party packages.
      const commit = repository
        ? await request(`https://api.github.com/repos/${repository}/commits/HEAD`, true)
        : null;
      if (commit?.sha) {
        for (const filename of [
          "LICENSE",
          "LICENSE.md",
          "LICENSE.txt",
          "license",
          "license.md",
          "LICENSE-MIT",
          "LICENCE",
          "COPYING",
        ]) {
          const url = `https://raw.githubusercontent.com/${repository}/${commit.sha}/${filename}`;
          const text = await request(url);
          if (typeof text === "string" && text.length > 100) {
            documents.push({
              path: filename,
              source: url,
              text: text.replaceAll("\r\n", "\n").trim(),
            });
            source = `https://github.com/${repository}/tree/${commit.sha}`;
            evidence = "upstream-license-review-required";
            break;
          }
        }
      }
    }
    if (!documents.length) {
      const identifier = value.license;
      const url = `https://raw.githubusercontent.com/spdx/license-list-data/main/json/details/${identifier}.json`;
      const details = /^[A-Za-z0-9.-]+$/u.test(identifier) ? await request(url, true) : null;
      if (details?.licenseText) {
        documents.push({
          path: `${identifier} (SPDX standard terms; upstream omitted license file)`,
          source: details.seeAlso?.[0] ?? url,
          text: details.licenseText.trim(),
        });
        evidence = "declared-spdx-review-required";
      } else {
        failures.push(`${name}@${value.version}`);
        continue;
      }
    }
    inventory.packages.push({
      path: key,
      name,
      version: value.version,
      license: value.license,
      purl: `pkg:npm/${name.replace("@", "%40")}@${value.version}`,
      integrity: value.integrity,
      resolved: value.resolved,
      source,
      evidence,
      attribution: {
        author: info?.author ?? null,
        contributors: info?.contributors ?? [],
        copyright: info?.copyright ?? null,
      },
      documents: documents.map(({ path: file, text, source: origin }) => {
        const hash = sha(text);
        inventory.texts[hash] = text;
        return { path: file, source: origin, sha256: hash };
      }),
    });
    if (inventory.packages.length % 100 === 0)
      console.log(`Collected notices: ${inventory.packages.length}/${packages.length}`);
  }
  mkdirSync(path.dirname(inventoryPath), { recursive: true });
  writeFileSync(inventoryPath, `${JSON.stringify(inventory, null, 2)}\n`);
  writeFileSync(textPath, render(inventory));
  if (failures.length)
    throw new Error(
      `LICENSE_TEXT_MISSING (partial inventory saved; resolve before release):\n${failures.join("\n")}`,
    );
  console.log(
    `THIRD_PARTY_NOTICES_UPDATED packages=${inventory.packages.length} texts=${Object.keys(inventory.texts).length}`,
  );
}

function check() {
  const inventory = JSON.parse(readFileSync(inventoryPath, "utf8"));
  if (inventory.lockSha256 !== sha(lockBytes))
    throw new Error("THIRD_PARTY_LOCK_STALE: run npm run notices:update");
  if (inventory.packages.length !== packages.length)
    throw new Error("THIRD_PARTY_INVENTORY_INCOMPLETE");
  for (const [index, [key, value]] of packages.entries()) {
    const item = inventory.packages[index];
    if (
      item.path !== key ||
      item.version !== value.version ||
      item.integrity !== value.integrity ||
      item.license !== value.license ||
      !item.documents.length
    )
      throw new Error(`THIRD_PARTY_ENTRY_STALE:${key}`);
    for (const document of item.documents)
      if (sha(inventory.texts[document.sha256] ?? "") !== document.sha256)
        throw new Error(`THIRD_PARTY_TEXT_INVALID:${key}`);
  }
  if (readFileSync(textPath, "utf8") !== render(inventory))
    throw new Error("THIRD_PARTY_RENDER_STALE");
  console.log(`THIRD_PARTY_NOTICES_OK packages=${packages.length}`);
  if (process.argv.includes("--release")) {
    const approval = JSON.parse(
      readFileSync(path.join(root, "third-party/review-status.json"), "utf8"),
    );
    if (
      approval.approved !== true ||
      approval.reviewedInventorySha256 !== sha(readFileSync(inventoryPath)) ||
      !approval.reviewer?.trim() ||
      !approval.reviewedAt ||
      !Number.isFinite(Date.parse(approval.reviewedAt))
    ) {
      throw new Error(
        "THIRD_PARTY_LEGAL_REVIEW_REQUIRED: see third-party/README.md; do not fabricate approval",
      );
    }
    console.log("THIRD_PARTY_LEGAL_REVIEW_RECORDED");
  }
}

try {
  if (process.argv.includes("--write")) await generate();
  else check();
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
}
